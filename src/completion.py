def main():
    """
      aris completion --generate-stub   write shell stub files to logs/
      aris completion --generate-cache — write shell cache files to logs/
      aris completion --test bash       test bash completion
      aris completion --test zsh        test zsh completion
      aris completion bash              print bash stub to stdout
      aris completion zsh               print zsh stub to stdout
    """
    ap = argparse.ArgumentParser(description="Generate shell completion (bash or zsh)")
    ap.add_argument("--root", required=True)
    ap.add_argument("shell", nargs="?", choices=["bash", "zsh"], help="Shell type (bash or zsh)")
    ap.add_argument(
        "--generate-cache",
        action="store_true",
        help="Generate/update completion cache files for both bash and zsh",
    )
    ap.add_argument(
        "--generate-stub",
        action="store_true",
        help="Generate/update completion stub files for both bash and zsh",
    )
    ap.add_argument(
        "--test",
        action="store_true",
        help="Test completion for specified shell (requires shell argument)",
    )
    args = ["--root", str(Path(__file__).parent.parent), "--generate-cache"]
    args = ap.parse_args(args)

    root = Path(args.root)

    if args.generate_cache:
        generate_cache(root)
    elif args.generate_stub:
        # Generate stubs for both shells
        generate_stub(root, "bash")
        generate_stub(root, "zsh")
    elif args.test:
        if not args.shell:
            print("Error: --test requires a shell argument (bash or zsh)", file=sys.stderr)
            return 1
        if args.shell == "zsh":
            return test_zsh_completion(root)
        else:
            return test_bash_completion(root)
    elif args.shell == "bash":
        # Print bash stub to stdout
        print(bash_stub(root))
    elif args.shell == "zsh":
        # Print zsh stub to stdout
        print(zsh_stub(root))
    
    return 0


if __name__ == "__main__":
    sys.exit(main())